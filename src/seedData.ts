export function encodeUtf8ToBase64(text: string): string {
  if (typeof Buffer !== 'undefined') {
    return Buffer.from(text, 'utf-8').toString('base64');
  }
  const bytes = new TextEncoder().encode(text);
  let binary = '';
  for (let i = 0; i < bytes.length; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary);
}

function escapeHtml(raw: string): string {
  return raw
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function buildWordDocFromCvText(cvText: string): string {
  const sectionHeadings = new Set([
    'PROFILE',
    'EXPERIENCE',
    'SELECTED PROJECTS',
    'TECHNICAL SKILLS',
    'EDUCATION',
    'LINKS',
    'INTERNSHIP CONTRIBUTIONS',
  ]);

  const lines = cvText.split(/\r?\n/);
  const bodyHtml = lines
    .map((line, idx) => {
      const trimmed = line.trim();
      if (!trimmed) return '<div style="height:6pt;"></div>';
      if (idx === 0) {
        return `<h1 style="font-size:18pt;margin:0 0 2pt 0;color:#0F172A;font-family:Calibri,Arial,sans-serif;">${escapeHtml(trimmed)}</h1>`;
      }
      if (idx === 1) {
        return `<div style="font-size:11pt;font-weight:bold;color:#2563EB;margin:0 0 4pt 0;font-family:Calibri,Arial,sans-serif;">${escapeHtml(trimmed)}</div>`;
      }
      if (sectionHeadings.has(trimmed.toUpperCase())) {
        return `<h2 style="font-size:11.5pt;margin:12pt 0 4pt 0;padding-bottom:2pt;border-bottom:1pt solid #CBD5E1;color:#0F172A;font-family:Calibri,Arial,sans-serif;">${escapeHtml(trimmed)}</h2>`;
      }
      if (trimmed.startsWith('•')) {
        return `<p style="margin:2pt 0 2pt 14pt;font-size:10.5pt;line-height:1.38;color:#1E293B;font-family:Calibri,Arial,sans-serif;">${escapeHtml(trimmed)}</p>`;
      }
      return `<p style="margin:2pt 0;font-size:10.5pt;line-height:1.38;color:#1E293B;font-family:Calibri,Arial,sans-serif;">${escapeHtml(trimmed)}</p>`;
    })
    .join('\n');

  return `<html xmlns:o="urn:schemas-microsoft-com:office:office"
xmlns:w="urn:schemas-microsoft-com:office:word"
xmlns="http://www.w3.org/TR/REC-html40">
<head>
<meta charset="utf-8" />
<title>Oguike Godswill CV</title>
<!--[if gte mso 9]>
<xml>
  <w:WordDocument>
    <w:View>Print</w:View>
    <w:Zoom>100</w:Zoom>
    <w:DoNotOptimizeForBrowser/>
  </w:WordDocument>
</xml>
<![endif]-->
<style>
  @page { margin: 0.65in; }
  body { font-family: Calibri, Arial, sans-serif; color: #0F172A; }
</style>
</head>
<body>
${bodyHtml}
</body>
</html>`;
}

export function buildTailoredCvText(
  baseCvText: string,
  roleTitle: string,
  descriptionText?: string
): { cvText: string; track: 'flutter_first' | 'react_first' } {
  const isFlutterRole =
    /\b(flutter|dart|mobile|ios|android|cross-platform)\b/i.test(roleTitle) ||
    /\bflutter\b/i.test(descriptionText || '');
  const track: 'flutter_first' | 'react_first' = isFlutterRole
    ? 'flutter_first'
    : 'react_first';

  const lines = baseCvText.split(/\r?\n/);
  if (lines.length > 1 && /^(FRONTEND|FLUTTER)/i.test(lines[1].trim())) {
    lines[1] = isFlutterRole
      ? 'FLUTTER & CROSS-PLATFORM ENGINEER (FLUTTER · DART · REACT · NEXT.JS · TYPESCRIPT)'
      : 'FRONTEND ENGINEER (REACT 19 · NEXT.JS 16 · TYPESCRIPT · TAILWIND CSS · FLUTTER)';
  }
  let tailored = lines.join('\n');

  if (!isFlutterRole) {
    const startMarker = '\nSELECTED PROJECTS\n';
    const endMarker = '\n\nTECHNICAL SKILLS\n';
    const startIdx = tailored.indexOf(startMarker);
    const endIdx = tailored.indexOf(endMarker);
    if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
      const sectionStart = startIdx + startMarker.length;
      const blocks = tailored
        .slice(sectionStart, endIdx)
        .split(/\n\n+/)
        .map((b) => b.trim())
        .filter(Boolean);

      const webPrimary = blocks.filter((b) =>
        /^(POCKETGUARD|MOLEARN|LEGITAUTOS|MENSAH HAIRLINE)\b/i.test(b)
      );
      const flutterBlocks = blocks.filter((b) =>
        /^(RUNBUDDY|SOLIS|VERSO)\b/i.test(b)
      );
      const otherBlocks = blocks.filter(
        (b) =>
          !/^(POCKETGUARD|MOLEARN|LEGITAUTOS|MENSAH HAIRLINE|RUNBUDDY|SOLIS|VERSO)\b/i.test(
            b
          )
      );

      if (webPrimary.length > 0 && flutterBlocks.length > 0) {
        const reordered = [...webPrimary, ...flutterBlocks, ...otherBlocks].join('\n\n');
        tailored =
          tailored.slice(0, sectionStart) + reordered + tailored.slice(endIdx);
      }
    }
  }

  return { cvText: tailored, track };
}

export function buildTailoredCvDocBase64(
  baseCvText: string,
  roleTitle: string,
  descriptionText?: string
): { base64: string; track: 'flutter_first' | 'react_first' } {
  const { cvText, track } = buildTailoredCvText(
    baseCvText,
    roleTitle,
    descriptionText
  );
  const docHtml = buildWordDocFromCvText(cvText);
  return { base64: encodeUtf8ToBase64(docHtml), track };
}

